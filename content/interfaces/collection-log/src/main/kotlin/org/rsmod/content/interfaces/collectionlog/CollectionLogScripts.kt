package org.rsmod.content.interfaces.collectionlog

import org.rsmod.api.type.builders.clientscript.ClientScriptBuilder

/**
 * Packs the one patched clientscript of the collection log,
 * `[proc,collection_search_display_item]`.
 *
 * The log's search draws every result with the count `-1`, which draws it grey, and leaves the real
 * count to a server that would have to run `collection_delayed_transmit` for each obtained item.
 * The server cannot know what was searched, so the patch makes the proc read the count itself from
 * the log inventory (`collection_transmit`, which this module keeps complete), as the category view
 * does. The file is generated by `tools/clog/gen_search_patch.py` from the cache's own script. If
 * the cache moves to a new revision, rerun the tool.
 *
 * The client reads scripts from the cache, so this needs `./gradlew packCache` to reach it.
 */
object CollectionLogScripts : ClientScriptBuilder() {
    override fun onPackCs2Task() {
        resourceFile<CollectionLogScripts>("cs2/[proc,collection_search_display_item]")
    }
}
