/**
 * Het's puzzle room data: the five layouts of walls and mirrors that rise from the floor in turn,
 * and the paths the orbs of darkness roll along. The layouts are read off the game (the walls and
 * mirrors are spawned by the server, not part of the map), as real tombs coordinates.
 */
enum class HetPiece {
    BreakInner,
    BreakEnd,
    SolidInner,
    SolidEnd,
    MirrorMovable,
    MirrorFixed,
}

