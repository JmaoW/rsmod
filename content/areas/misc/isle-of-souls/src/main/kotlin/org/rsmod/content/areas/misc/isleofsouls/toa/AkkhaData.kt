/**
 * Akkha's arena data, read off the game as real tombs coordinates: where the unstable orbs of the
 * final stand may start (and roll), and the columns of floor that make up each of the four
 * quadrants.
 */
enum class AkkhaDirection(val dx: Int, val dz: Int) {
    North(0, 1),
    South(0, -1),
    East(1, 0),
    West(-1, 0),
    NorthEast(1, 1),
    NorthWest(-1, 1),
    SouthEast(1, -1),
    SouthWest(-1, -1),
}

class AkkhaOrbPath(val x: Int, val z: Int, val direction: AkkhaDirection)

/** A run of floor in one column of a quadrant: x, first z, last z. */
class AkkhaColumn(val x: Int, val firstZ: Int, val lastZ: Int)

