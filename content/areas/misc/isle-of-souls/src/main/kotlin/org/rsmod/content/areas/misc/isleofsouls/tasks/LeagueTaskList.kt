/** The league difficulty tiers and the points each task of that tier awards. */
internal enum class LeagueTier(val points: Int, val label: String) {
    Easy(points = 10, label = "easy"),
    Medium(points = 30, label = "medium"),
    Hard(points = 80, label = "hard"),
    Elite(points = 200, label = "elite"),
    Master(points = 400, label = "master"),
}

