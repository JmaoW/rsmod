/**
 * A league task that is completed by killing monsters called [monster] (any letter case): once, or
 * [count] times for a counted task, whose progress is kept in the progress varp [LeagueKillTasks]
 * pairs it with.
 */
internal data class KillTask(val taskId: Int, val monster: String, val count: Int = 1)

/**
 * Completes the league's kill tasks ("Defeat a Goblin", "Kill 30 Bandits"). The kill goes to the
 * player who did the most damage, and to their team, as with any task.
 *
 * The tasks are the ones in the Raging Echoes list that name one kind of monster, without a special
 * way of killing it (no spell, weapon, time limit or Slayer task). Their place words are gone from
 * the text ("Defeat a Kurask in Tirannwn" is "Defeat a Kurask") since every monster is in the one
 * open world. The list is generated by `tools/drops/kill_tasks.py`. Kill ladders of bosses (50, 150
 * and 300 kills) come with the boss fights, not here.
 */
class LeagueKillTasks @Inject constructor(private val tracker: LeagueTaskTracker) : PluginScript() {
    override fun ScriptContext.startup() {
        onEvent<NpcDeathEvents.Killed> {
            val hero = hero ?: return@onEvent
            kill(hero, npc.visType.name)
        }
    }

    /** [player] killed a monster called [name]. */
    internal fun kill(player: Player, name: String) {
        val tasks = byMonster[name.trim().lowercase()] ?: return
        for (task in tasks) {
            val counter = counters[task.taskId]
            if (counter == null) {
                tracker.complete(player, task.taskId)
            } else {
                tracker.addProgress(player, task.taskId, counter, task.count)
            }
        }
    }

