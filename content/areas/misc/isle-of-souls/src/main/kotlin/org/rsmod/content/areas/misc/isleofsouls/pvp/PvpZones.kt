package org.rsmod.content.areas.misc.isleofsouls.pvp

import org.rsmod.content.areas.misc.isleofsouls.dungeons.Dungeon
import org.rsmod.content.areas.misc.isleofsouls.wilderness.EscapeCaves
import org.rsmod.content.areas.misc.isleofsouls.wilderness.WildLair
import org.rsmod.map.CoordGrid

/**
 * The places players can be allowed to fight each other. Whether a zone is open is the event
 * settings' call ([PvpSettings]); this only says where each one is.
 */
enum class PvpZone(val key: String, val title: String) {
    SoulWarsArena("soulWarsArena", "the Soul Wars arena"),
    RevenantCaves("revenantCaves", "the Revenant Caves"),
    WildernessBossLairs("wildernessBossLairs", "the Wilderness boss lairs"),
    EscapeCavesZone("escapeCaves", "the Escape Caves");

    /** Whether [coords] is inside the zone. */
    operator fun contains(coords: CoordGrid): Boolean =
        when (this) {
            SoulWarsArena -> coords in PvpAreas.SOUL_WARS_ARENA
            RevenantCaves -> Dungeon.REVENANT_CAVES.areas.any { coords in it }
            WildernessBossLairs -> WildLair.containing(coords) != null
            EscapeCavesZone -> coords in EscapeCaves.area
        }
}

object PvpAreas {
    /** The Soul Wars arena's playable ground; see [ArenaTiles]. */
    val SOUL_WARS_ARENA: ArenaTiles by lazy { ArenaTiles.load("soul_wars_arena.txt") }
}

/**
 * A set of tiles on level 0, stored as inclusive x ranges for each z. The Soul Wars arena is ringed
 * by a wall of map-edge forest, with pockets of floor behind it that are not part of the arena, so
 * a rectangle round it would be wrong.
 *
 * The resource has one line per z, `z x0-x1 x0-x1 ...`, and is generated by
 * `tools/dungeons/soulwars_arena.py`: every tile walkable from either team's graveyard portal, with
 * the team barriers counted as open.
 */
class ArenaTiles(private val rows: Map<Int, IntArray>) {
    val size: Int =
        rows.values.sumOf { ranges ->
            ranges.indices.step(2).sumOf { ranges[it + 1] - ranges[it] + 1 }
        }

    operator fun contains(coords: CoordGrid): Boolean {
        if (coords.level != 0) {
            return false
        }
        val ranges = rows[coords.z] ?: return false
        for (i in ranges.indices step 2) {
            if (coords.x in ranges[i]..ranges[i + 1]) {
                return true
            }
        }
        return false
    }

    companion object {
        fun load(name: String): ArenaTiles {
            val stream =
                checkNotNull(ArenaTiles::class.java.getResourceAsStream(name)) {
                    "Missing resource $name"
                }
            return parse(stream.bufferedReader().readText())
        }

        fun parse(text: String): ArenaTiles {
            val rows = HashMap<Int, IntArray>()
            for (line in text.lineSequence().filter { it.isNotBlank() }) {
                val parts = line.trim().split(' ')
                val ranges = IntArray((parts.size - 1) * 2)
                for ((i, range) in parts.drop(1).withIndex()) {
                    val (from, to) = range.split('-').map(String::toInt)
                    ranges[i * 2] = from
                    ranges[i * 2 + 1] = to
                }
                rows[parts[0].toInt()] = ranges
            }
            return ArenaTiles(rows)
        }
    }
}

/** Which of the open zones a tile is in. */
object PvpZones {
    /** The zone at [coords] that [settings] has open, or `null` when players cannot fight there. */
    fun open(coords: CoordGrid, settings: PvpSettings): PvpZone? =
        PvpZone.entries.firstOrNull { settings.isOpen(it) && coords in it }
}

/** Which zones are open for player-versus-player combat: all closed unless the file opens them. */
data class PvpSettings(
    val soulWarsArena: Boolean = false,
    val revenantCaves: Boolean = false,
    val wildernessBossLairs: Boolean = false,
    val escapeCaves: Boolean = false,
) {
    fun isOpen(zone: PvpZone): Boolean =
        when (zone) {
            PvpZone.SoulWarsArena -> soulWarsArena
            PvpZone.RevenantCaves -> revenantCaves
            PvpZone.WildernessBossLairs -> wildernessBossLairs
            PvpZone.EscapeCavesZone -> escapeCaves
        }

    companion object {
        /** The keys of the `pvp` object in the settings file. */
        val KEYS: Set<String> = PvpZone.entries.map { it.key }.toSet()
    }
}
