package org.rsmod.content.skills.smithing.configs

import org.rsmod.game.type.obj.ObjType

/**
 * Something an anvil can make.
 *
 * @property slot the position of the item's button in the anvil interface, see
 *   [SmithingComponents.slots].
 * @property label what the interface calls the item, such as `Plate body`.
 * @property bars how many bars it costs.
 * @property quantity how many of [obj] one smith gives (arrowtips and nails come in stacks).
 */
internal class SmithingProduct(
    val metal: SmithingMetal,
    val slot: Int,
    val obj: ObjType,
    val label: String,
    val level: Int,
    val bars: Int,
    val quantity: Int,
) {
    val xp: Double
        get() = bars * metal.xpPerBar
}

