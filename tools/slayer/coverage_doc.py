"""Writes docs/isle_of_souls_slayer_coverage.md from tools/slayer/coverage.json (run coverage.py first)."""
import collections, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
cov = json.load(open(os.path.join(HERE, "coverage.json")))
reg = json.load(open(os.path.join(HERE, "dead_task_regions.json")))
data = json.load(open(os.path.join(HERE, "slayer_data.json")))

dead = sorted([c for c in cov.values() if c["reachable"] == 0], key=lambda c: c["name"])
live = sorted([c for c in cov.values() if c["reachable"] > 0], key=lambda c: (c["reachable"], c["name"]))
dead_ids = {int(k) for k, c in cov.items() if c["reachable"] == 0}
dead_unv = sorted(c["name"] for c in cov.values() if c["reachable"] + c["unverified"] == 0)


def ms(c):
    return ", ".join(m.capitalize() for m in c["masters"])


def where(c):
    return ", ".join(f"{k} {v}" for k, v in sorted(c["areas"].items(), key=lambda kv: -kv[1])
                     if k not in ("unverified", "unreachable"))


# per-master shares
master_rows = []
keeps = {}
for m, v in data["masters"].items():
    tot = sum(t["weight"] for t in v["tasks"])
    d = sum(t["weight"] for t in v["tasks"] if t["taskId"] in dead_ids)
    thin = sum(t["weight"] for t in v["tasks"] if 0 < cov[str(t["taskId"])]["reachable"] < 10)
    nd = sum(1 for t in v["tasks"] if t["taskId"] in dead_ids)
    keeps[m] = (len(v["tasks"]) - nd, len(v["tasks"]))
    master_rows.append(f"| {m.capitalize()} | {len(v['tasks'])} | {nd} | **{100 * d / tot:.0f}%** | {100 * thin / tot:.0f}% |")

# tasks fed by each dungeon / isle
per_area = collections.defaultdict(list)
for c in cov.values():
    for k, n in c["areas"].items():
        if k not in ("unverified", "unreachable"):
            per_area[k].append((c["name"], n))
area_rows = []
for k, lst in sorted(per_area.items(), key=lambda kv: -len(kv[1])):
    lst.sort(key=lambda t: -t[1])
    area_rows.append(f"| {k} | {len(lst)} | {sum(n for _, n in lst)} | " + ", ".join(f"{a} {n}" for a, n in lst) + " |")

L = []
L.append(f"""# Isle of Souls: Slayer tasks against reachable monsters

Written 2026-10-12. Numbers are generated by `python tools/slayer/coverage.py` (output in
`tools/slayer/coverage.txt` and `coverage.json`) and this page by `coverage_doc.py`; rerun both after adding
dungeons or spawns.

## What was compared

- **Tasks:** every task the three masters can give (Turael 24, Vannaka 41, Duradel 36; {len(cov)} distinct
  tasks), with the npc types that count for each, from `tools/slayer/slayer_data.json`.
- **Monsters:** the 22,715 world spawns in `osrs-npc-spawns` (surface, underground, revenants).
- **Reachable:** a walking flood fill (`tools/dungeons/collision.py`, doors and interactive objects
  passable) from the isle plaza and from each of the 18 dungeon arrivals, plus the dungeon Agility
  crossings. A spawn is **verified** when a flooded tile on its level lies within 2 tiles.
  **Unverified** means the spawn is inside one of a dungeon's map rectangles but the flood did not
  reach it (see Caveats). Everything else is mainland, or a cave with no entrance on the isle.

## Result

**{len(dead)} of the {len(cov)} tasks have no verified spawn** ({len(dead_unv)} if every unverified spawn counts).
The engine only drops a task when no spawn exists *anywhere in the world*, so all of them can still be
assigned, and then cannot be done. Share of each master's assignments (by weight) that land on one:

| Master | Tasks | Dead tasks | Share of assignments | Plus thin (under 10 monsters) |
|---|---|---|---|---|
""" + "\n".join(master_rows) + """

Roughly two assignments in five are undoable as things stand.

### Dead tasks (no reachable monster)

| Task | Master | World spawns | Biggest clusters (64x64 map squares, x-range,z-range) |
|---|---|---|---|""")
for c in dead:
    r = "; ".join(f"{a} ({n})" for a, n in reg.get(c["name"], []))
    L.append(f"| {c['name']} | {ms(c)} | {c['world']} | {r} |")

L.append("""
Recognisable clusters (my reading of the coordinates): Slayer Tower (3392,3520: crawling hands, infernal
mages), Lumbridge Swamp caves (3136,9536: cave bugs, cave slimes), Stronghold of Security (1856,5184:
minotaurs, goblins), God Wars Dungeon (2816-2943,5248-5375: aviansies, spiritual creatures), Asgarnia Ice
Dungeon (3008,9536: skeletal wyverns, ice warriors), Karuulm (1216-1343,10176: drakes, wyrms), Fossil
Island (3584,10176: wyverns), Shayzien (1472,3648: lizardmen), Mourner Tunnels (1984,4608: dark beasts),
Morytania (3392-3647,3200-3519: ghouls, vampyres), Kharidian desert (3392,3008: lizards). Surface
squares (z under 4032) are the mainland.

### Tasks that can be done, fewest reachable monsters first

| Task | Master | Verified | Where | Unverified (inside a dungeon map, not walk-reachable) |
|---|---|---|---|---|""")
for c in live:
    u = ", ".join(f"{k} {v}" for k, v in c["unverifiedWhere"].items())
    L.append(f"| {c['name']} | {ms(c)} | {c['reachable']} of {c['world']} | {where(c)} | {u} |")

L.append("""
## What each place supplies

Verified spawns only: how many task lists a place feeds and how many monsters that is in all.

| Place | Tasks | Monsters | Detail |
|---|---|---|---|
""" + "\n".join(area_rows))

L.append(f"""
## Caveats

1. **Unverified is mostly the flood model.** The Catacombs has about 90 unverified task spawns on tiles my
   collision model thinks are blocked; that reads as a model gap, not a closed area (the dungeon audit passes
   there), so treat them as probably reachable. The Taverley rectangle also covers other caves: 117 spawns
   sit in separate cut-off pockets (60 to 3,800 tiles each), among them the hill giants, dwarves, ice
   warriors and ice giants, which are probably not reachable from the entrance. Brimhaven's 22 metal
   dragons are past the log balance and crevice route, which the dungeon plan lists as not built.
2. **Level.** Taverley's blue and black dragons are on level 1 coordinates and the flood only covers the
   level it starts on, so those 18 are unverified.
3. The flood ignores Agility level gates, so a verified spawn can still need a shortcut the player lacks.
4. Spawns added by scripts (superiors, kraken reveals) are not in the toml files, so those counts are floors.
5. The Leagues combat window and unlock bits are ignored here: a task is counted for a master whatever the player.

## Options

1. **Stop assigning dead tasks (cheap, recommended first).** Write each task's reachable count into
   `tasks.tsv` from `build_data.py` and have the engine skip tasks under a minimum. That removes
   {len(dead)} tasks: Turael keeps {keeps['turael'][0]} of {keeps['turael'][1]}, Vannaka {keeps['vannaka'][0]} of
   {keeps['vannaka'][1]}, Duradel {keeps['duradel'][0]} of {keeps['duradel'][1]}. If a master has nothing left for a player the
   engine already falls back to the open list.
2. **Add monsters by copying spawns** onto the isle or into an existing dungeon, as done for the
   revenants. Biggest wins: Slayer Tower floors (crawling hands, infernal mages), Lumbridge Swamp caves
   (cave bugs, cave slimes), Stronghold of Security (minotaurs), Asgarnia Ice Dungeon (skeletal wyverns,
   ice warriors).
3. **Add whole dungeons** with entrances like the other 18: Karuulm (drakes, wyrms), Mourner Tunnels (dark
   beasts), God Wars (aviansies, spiritual creatures), Fossil Island caves, Shayzien (lizardmen).
4. **Leave the surface long tail** (elves, trolls, ogres, sea snakes, crocodiles, bears, wolves, goblins,
   vampyres, ghouls) to option 1.
""")
open(os.path.join(ROOT, "docs", "isle_of_souls_slayer_coverage.md"), "w").write("\n".join(L))
print("written;", len(dead), "dead")
