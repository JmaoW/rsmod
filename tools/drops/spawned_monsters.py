#!/usr/bin/env python3
"""Lists the wiki pages of every attackable npc the world spawns, for wiki_import.py.

    python tools/drops/spawned_monsters.py            # writes tools/drops/monsters_spawned.txt
    python tools/drops/spawned_monsters.py --fetch    # download the osrsreboxed-db files again

An npc name like "Guard" or "Man" is ambiguous on the wiki, so the page of each npc id comes from
osrsreboxed-db's `npc-drops.json` (id -> wiki page, with `monsters-complete.json` as a fallback), cached in tools/drops/.cache. Spawned npc ids
come from the generated spawn files (tools/spawns), and "attackable" is the same test that
tools/spawns/gaps.py uses. monsters.txt (hand-written lines) is read first by the importer, so a
page listed there keeps its own options.

Also writes tools/drops/spawned_npcs.json: every spawned attackable npc id with its name, spawn
count and wiki page, which coverage.py uses to find the ids that still have no drop table.
"""

import argparse
import collections
import json
import re
import sys
import urllib.request
from pathlib import Path

TOOL_DIR = Path(__file__).resolve().parent
sys.path.insert(0, str(TOOL_DIR.parent / "spawns"))
import convert  # noqa: E402
import gaps  # noqa: E402

CACHE_DIR = TOOL_DIR / ".cache"
BASE = "https://raw.githubusercontent.com/RSPSApp/osrsreboxed-db/master/docs/"
USER_AGENT = "rsmod-isle-of-souls-dropimport/0.3"


def db_file(name, fetch):
    CACHE_DIR.mkdir(exist_ok=True)
    path = CACHE_DIR / ("rb_" + Path(name).name)
    if fetch or not path.exists():
        request = urllib.request.Request(BASE + name, headers={"User-Agent": USER_AGENT})
        with urllib.request.urlopen(request, timeout=300) as response:
            path.write_bytes(response.read())
    return json.loads(path.read_text(encoding="utf-8"))


def attackable(v):
    return v["name"] and v["level"] > 0 and any("ttack" in (o or "") for o in v["ops"])


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    parser.add_argument("--fetch", action="store_true", help="download the db files again")
    args = parser.parse_args()

    db_npcs = db_file("drops-json/npc-drops.json", args.fetch)["npcs"]
    db_monsters = db_file("monsters-complete.json", args.fetch)
    npcs = convert.load_cache_npcs()
    written = gaps.written_ids()

    rows = {}
    pages = collections.OrderedDict()
    for npc_id in sorted(written):
        v = npcs.get(npc_id)
        if not v or not attackable(v):
            continue
        entry = db_npcs.get(str(npc_id))
        page = entry["wiki_page"] if entry else None
        fallback = False
        if page is None:
            # No drop table in the db for this id: its wiki page may still have one (the db
            # skips some variants). The monster entry's wiki name is often a label such as
            # "Duck (Female)", so use the page name without the bracket, and hand the importer
            # the id because the page's infobox may not list it.
            page = re.sub(r"\s*\(.*\)$", "", (db_monsters.get(str(npc_id)) or {}).get("wiki_name") or "")
            page = page or None
            fallback = True
        rows[npc_id] = {"name": v["name"], "level": v["level"], "spawns": written[npc_id],
                        "page": page}
        if page:
            pages.setdefault(page, [])
            if fallback:
                pages[page].append(npc_id)

    lines = ["# GENERATED by tools/drops/spawned_monsters.py: the wiki page of every attackable npc",
             "# the world spawns. Do not hand-edit; put pages that need options in monsters.txt.", ""]
    for page in sorted(pages, key=str.lower):
        extra = sorted(set(pages[page]))
        lines.append(f"{page} | ids={','.join(map(str, extra))}" if extra else page)
    (TOOL_DIR / "monsters_spawned.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (TOOL_DIR / "spawned_npcs.json").write_text(json.dumps(rows, indent=0), encoding="utf-8")

    missing = [r for r in rows.values() if not r["page"]]
    print(f"{len(rows)} spawned attackable npc types -> {len(pages)} wiki pages; "
          f"{len(missing)} types ({sum(r['spawns'] for r in missing)} spawns) have no page in the db")


if __name__ == "__main__":
    main()
