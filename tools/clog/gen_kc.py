#!/usr/bin/env python3
"""Generates the collection log's kill-count counters from the vanilla cache.

    python tools/clog/gen_kc.py

The kill-count lines under a collection log category come from cs2 2735 (`collection_category_count`):
a switch on the category struct id whose cases push a label and one of the three shared client
varps (2048 / 2941 / 2942). This tool reads the script, pairs every label with its varp slot and
writes:

* content/interfaces/collection-log/.../CollectionKillCountData.kt: one saved server varp per
  distinct label (`clog_kc_<label>`), plus the table category struct -> counter per client varp.
* the matching `varp.sym` lines (appended, only when missing), numbered downwards from the lowest
  custom id. New varp names need a packCache.

Two categories showing the same label (the normal and "(Rare)" clue categories) share a counter.
"""

import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools/spawns"))
import js5  # noqa: E402

SCRIPT_ID = 2735
VARP_NAMES = {2048: 0, 2941: 1, 2942: 2}
OUT_KT = (
    ROOT
    / "content/interfaces/collection-log/src/main/kotlin/org/rsmod/content/interfaces/collectionlog/CollectionKillCountData.kt"
)
VARP_SYM = ROOT / ".data/symbols/varp.sym"
VARBIT_NAMES = {11961, 11960}


class Buf:
    def __init__(self, d):
        self.d, self.p = d, 0

    def u8(self):
        v = self.d[self.p]
        self.p += 1
        return v

    def u16(self):
        v = int.from_bytes(self.d[self.p:self.p + 2], "big")
        self.p += 2
        return v

    def i32(self):
        v = int.from_bytes(self.d[self.p:self.p + 4], "big", signed=True)
        self.p += 4
        return v

    def string(self):
        e = self.d.index(0, self.p)
        s = self.d[self.p:e].decode("cp1252")
        self.p = e + 1
        return s


def load_script(sid):
    b = js5.read_group(12, sid)
    sw_len = struct.unpack(">H", b[-2:])[0]
    end = len(b) - 2 - sw_len
    n_instr = struct.unpack(">i", b[end - 12:end - 8])[0]
    d = Buf(b)
    d.string()
    ins = []
    while len(ins) < n_instr:
        op = d.u16()
        if op == 3:
            val = d.string()
        elif op < 100 and op not in (21, 38, 39):
            val = d.i32()
        else:
            val = d.u8()
        ins.append((op, val))
    # switch tables
    p = end
    count = b[p]
    p += 1
    tables = []
    for _ in range(count):
        cnt = struct.unpack(">H", b[p:p + 2])[0]
        p += 2
        t = {}
        for _ in range(cnt):
            k, j = struct.unpack(">ii", b[p:p + 8])
            p += 8
            t[k] = j
        tables.append(t)
    return ins, tables


def slug(label):
    s = label.lower().replace("'", "").replace('"', "")
    s = re.sub(r"[^a-z0-9]+", "_", s).strip("_")
    return s


def main():
    ins, tables = load_script(SCRIPT_ID)
    switch_at = next(i for i, (op, _) in enumerate(ins) if op == 60)
    table = tables[0]
    skip = {"", "<col=ffffff>", "</col>"}
    cats = {}
    for struct_id, jump in sorted(table.items()):
        i = switch_at + 1 + jump
        strings, lines = [], []
        while i < len(ins):
            op, v = ins[i]
            if op == 3:
                if v not in skip:
                    strings.append(v.strip().strip('"'))
            elif op == 1 and v in VARP_NAMES:
                label = strings[0] if strings else ""
                lines.append((label, VARP_NAMES[v]))
                strings = []
            elif op == 25 and v in VARBIT_NAMES:
                strings = []
            elif op == 21:
                break
            i += 1
        if lines:
            cats[struct_id] = lines

    counters = {}  # slug -> label
    for lines in cats.values():
        for label, _slot in lines:
            counters.setdefault(slug(label), label)
    names = sorted(counters)

    kt = [
        "// Generated by tools/clog/gen_kc.py from cs2 2735 (collection_category_count). Do not edit.",
        "package org.rsmod.content.interfaces.collectionlog",
        "",
        "import org.rsmod.api.type.builders.varp.VarpBuilder",
        "import org.rsmod.api.type.refs.varp.VarpReferences",
        "import org.rsmod.game.type.varp.VarpType",
        "",
        "/** One saved counter for each distinct kill-count line the collection log can show. */",
        "internal object CollectionKillCountVarps : VarpReferences() {",
    ]
    for n in names:
        kt.append(f'    val {n} = find("clog_kc_{n}")')
    kt += ["}", "", "internal object CollectionKillCountBuilder : VarpBuilder() {", "    init {"]
    for n in names:
        kt.append(f'        build("clog_kc_{n}") {{}}')
    kt += ["    }", "}", "", "internal object CollectionKillCountData {"]
    kt += [
        "    /**",
        "     * Category struct id -> the counter shown on each of the three client varps",
        "     * (`collection_category_count`, `_count2`, `_count3`), `null` where the line is unused.",
        "     */",
        "    val byCategory: Map<Int, List<VarpType?>> =",
        "        mapOf(",
    ]
    for struct_id, lines in sorted(cats.items()):
        slots = [None, None, None]
        for label, slot in lines:
            slots[slot] = slug(label)
        items = ", ".join("null" if s is None else f"CollectionKillCountVarps.{s}" for s in slots)
        kt.append(f"            {struct_id} to listOf({items}),")
    kt += ["        )", "", "    /** Every counter, with the line label the client shows for it. */"]
    kt.append("    val all: List<Pair<VarpType, String>> =")
    kt.append("        listOf(")
    for n in names:
        label = counters[n].replace('"', '\\"')
        kt.append(f'            CollectionKillCountVarps.{n} to "{label}",')
    kt += ["        )", "}", ""]
    OUT_KT.parent.mkdir(parents=True, exist_ok=True)
    OUT_KT.write_bytes("\r\n".join(kt).encode("utf-8"))

    sym = VARP_SYM.read_bytes().decode("utf-8")
    existing = {m.group(2) for m in re.finditer(r"^(\d+)\t(\S+)", sym, re.M)}
    used = [int(m.group(1)) for m in re.finditer(r"^(\d+)\t", sym, re.M)]
    custom = [u for u in used if u >= 60000]
    next_id = min(custom) - 1
    added = 0
    if not sym.endswith("\n"):
        sym += "\r\n"
    for n in names:
        full = f"clog_kc_{n}"
        if full in existing:
            continue
        sym += f"{next_id}\t{full}\r\n"
        next_id -= 1
        added += 1
    VARP_SYM.write_bytes(sym.encode("utf-8"))
    print(f"{len(cats)} categories, {len(names)} counters, {added} new varp.sym lines")


if __name__ == "__main__":
    main()
