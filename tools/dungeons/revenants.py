"""Writes the revenant spawns the world spawn list lacks.

The OSRS Wiki's Revenant Caves page lists how many of each revenant the caves hold (30 in all); the
2023 rs-map-viewer list has 15 of them, one anchor per spawn it knew. The missing ones are put on
walkable tiles of the cave near the anchor of their own type (never within 10 tiles of an entrance
and never closer than 8 tiles to another of the same type). The positions are mine, not Jagex's.

Usage: python tools/dungeons/revenants.py      (rewrites revenants.toml)
"""
import os, random, re, sys
sys.path.insert(0, os.path.dirname(__file__))
import collision as K

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
MOD = os.path.join(ROOT, "content", "areas", "misc", "osrs-npc-spawns", "src", "main", "resources",
                   "org", "rsmod", "content", "areas", "misc", "osrsnpcspawns")
WIKI = {  # npc sym -> (wiki name, quantity on the wiki's Revenant Caves page)
    "wild_cave_imp": ("Revenant imp", 4), "wild_cave_goblin": ("Revenant goblin", 2),
    "wild_cave_pyrefiend": ("Revenant pyrefiend", 4), "wild_cave_hobgoblin": ("Revenant hobgoblin", 2),
    "wild_cave_cyclops": ("Revenant cyclops", 2), "wild_cave_hellhound": ("Revenant hellhound", 2),
    "wild_cave_demon": ("Revenant demon", 4), "wild_cave_ork": ("Revenant ork", 4),
    "wild_cave_darkbeast": ("Revenant dark beast", 2), "wild_cave_knight": ("Revenant knight", 2),
    "wild_cave_dragon": ("Revenant dragon", 2),
}
ENTRANCES = [(3217, 10058), (3244, 10215)]

text = open(os.path.join(MOD, "underground.toml")).read()
have = {k: [] for k in WIKI}
for n, c in re.findall(r"npc = '([^']+)'\ncoords = '([^']+)'", text):
    if n in WIKI:
        l, mx, mz, lx, lz = map(int, c.split("_"))
        have[n].append((mx * 64 + lx, mz * 64 + lz))

cave = K.flood(0, 3217, 10058, 20000)
rng = random.Random(233)
taken = [p for v in have.values() for p in v]
out = []
for sym, (wiki, qty) in WIKI.items():
    anchors = list(have[sym])
    need = qty - len(anchors)
    for i in range(max(need, 0)):
        anchor = anchors[i % len(anchors)]
        pool = [t for t in cave
                if 12 <= max(abs(t[0] - anchor[0]), abs(t[1] - anchor[1])) <= 35
                and all(max(abs(t[0] - e[0]), abs(t[1] - e[1])) > 10 for e in ENTRANCES)
                and all(max(abs(t[0] - o[0]), abs(t[1] - o[1])) > 8 for o in have[sym])
                and all(max(abs(t[0] - o[0]), abs(t[1] - o[1])) > 3 for o in taken)
                and sum(((t[0] + dx, t[1] + dz) in cave) for dx in (-1, 0, 1) for dz in (-1, 0, 1)) == 9]
        pool.sort()
        t = pool[rng.randrange(len(pool))]
        have[sym].append(t); taken.append(t)
        out.append((sym, t))
lines = ["# Generated by tools/dungeons/revenants.py. Do not edit; re-run the script.\n"]
for sym, (x, z) in out:
    lines.append(f"\n[[spawn]]\nnpc = '{sym}'\ncoords = '0_{x // 64}_{z // 64}_{x % 64}_{z % 64}'\n")
open(os.path.join(MOD, "revenants.toml"), "w").write("".join(lines))
print(len(out), "revenants added;", sum(len(v) for v in have.values()), "in the caves in all")
for sym, t in out: print(" ", WIKI[sym][0], t)
