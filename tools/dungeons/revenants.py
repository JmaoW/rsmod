"""Writes the Revenant Caves' 30 revenant spawns, read off the OSRS Wiki's map of the caves.

The map draws one square per spawn, coloured by type (imp, goblin, pyrefiend, hobgoblin, cyclops,
hellhound, demon, ork, dark beast, knight, dragon: 4/2/4/2/2/2/4/4/2/2/2). The map is 4 pixels to a
tile; its cave outline was fitted to the cache's walkable tiles (flood from the lower entrance) and
the marker centres converted to tiles, each checked to be a walkable cave tile. Markers are 10 px
(2.5 tiles) wide, so a spot can be a tile off the real one.

tools/spawns/exclusions.txt drops the source list's own revenants (only 15, and at other spots), so
this file is the only place they come from.

Usage: python tools/dungeons/revenants.py      (rewrites revenants.toml)
"""
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
MOD = os.path.join(ROOT, "content", "areas", "misc", "osrs-npc-spawns", "src", "main", "resources",
                   "org", "rsmod", "content", "areas", "misc", "osrsnpcspawns")
SPAWNS = {  # npc sym -> tiles read off the wiki map
    "wild_cave_imp": [(3212, 10196), (3218, 10187), (3203, 10074), (3196, 10069)],
    "wild_cave_goblin": [(3227, 10074), (3223, 10065)],
    "wild_cave_pyrefiend": [(3169, 10157), (3248, 10151), (3184, 10151), (3253, 10142)],
    "wild_cave_hobgoblin": [(3247, 10103), (3240, 10095)],
    "wild_cave_cyclops": [(3167, 10195), (3176, 10184)],
    "wild_cave_hellhound": [(3248, 10174), (3239, 10160)],
    "wild_cave_demon": [(3180, 10200), (3186, 10191), (3169, 10116), (3152, 10111)],
    "wild_cave_ork": [(3231, 10133), (3215, 10128), (3220, 10094), (3208, 10093)],
    "wild_cave_darkbeast": [(3200, 10165), (3215, 10163)],
    "wild_cave_knight": [(3228, 10220), (3209, 10215)],
    "wild_cave_dragon": [(3231, 10201), (3244, 10198)],
}

lines = ["# Generated by tools/dungeons/revenants.py. Do not edit; re-run the script.\n"]
for sym, tiles in SPAWNS.items():
    for x, z in tiles:
        lines.append(f"\n[[spawn]]\nnpc = '{sym}'\ncoords = '0_{x // 64}_{z // 64}_{x % 64}_{z % 64}'\n")
open(os.path.join(MOD, "revenants.toml"), "w", newline="\n").write("".join(lines))
print(sum(len(t) for t in SPAWNS.values()), "revenants written")
